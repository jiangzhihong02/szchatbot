/** 口岸段落：每個口岸一行，全部取自 `BORDERS`（繁體正本）。 */
function borderBlock(): string {
  const modes = messages["zh-Hant"].engine.borderMode;
  const lines = BORDERS.map((b) => {
    // 用 ⇄ 而非括號：`nameSz` 自己可能已帶括號（高鐵西九龍的深方是「深圳北 / 福田（高鐵站）」），
    // 套起來會變成括號裡還有括號。
    const name = b.nameSz && b.nameSz !== b.nameHk ? `${b.nameHk} ⇄ ${b.nameSz}` : b.nameHk;
    const how = b.modes.map((m) => modes[m]).join("／");
    const tip = b.tip ? `｜${b.tip}` : "";
    return `· ${name} ${b.hours}｜${how}｜港側 ${b.hkAccess}｜深側 ${b.szAccess}｜${b.note}${tip}`;
  });
  return [
    "【口岸】以下為已知口岸，開放時間與接駁**一律以此為準**：",
    ...lines,
    "**未列於上者（例如皇崗／新皇崗口岸），不要給出具體開放時間、也不要說它已開通或何時開通**——本站尚未取得運營方確認，遇到相關提問請旅客以官方公布為準。",
  ].join("\n");
}

