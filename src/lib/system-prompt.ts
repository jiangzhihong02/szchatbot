export const SYSTEM_PROMPT = `${PROMPT_HEAD}\n\n${borderBlock()}\n\n${PROMPT_TAIL}`;

/** 依界面語言指定回答語言（票 11 共識第 5 條）。 */
const LANG_DIRECTIVE: Record<Locale, string> = {
  "zh-Hant": "\n\n【語言】無論使用者用什麼語言提問，一律用**繁體中文**回答。",
  "zh-Hans": "\n\n【语言】无论用户用什么语言提问，一律用**简体中文**回答。",
  en: "\n\n[Language] Whatever language the user writes in, always answer in English.",
};

export function systemPromptFor(locale: Locale): string {
  return SYSTEM_PROMPT + LANG_DIRECTIVE[locale];
}
